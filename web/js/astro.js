  /* 给定时刻（jd, UT），返回所处节气：
     {seasonID, name, startJD, endJD, index(第几个节气)} */
  function seasonAt(jd) {
    // 用北京时间的年做基准
    var bj = fromJulian(jd + 8 / 24);
    var y = bj.y;
    var best = null;
    for (var yy = y - 1; yy <= y + 1; yy++) {
      for (var s = 1; s <= 24; s++) {
        var t = /* memo */ solarTermJD(yy, s);
        if (t <= jd + 1e-9) {
          if (!best || t > best.startJD) best = { seasonID: s, startJD: t, year: yy };
        }
      }
    }
    var nxt = null;
    for (var yy2 = y - 1; yy2 <= y + 1; yy2++) {
      for (var s2 = 1; s2 <= 24; s2++) {
        var t2 = solarTermJD(yy2, s2);
        if (t2 > jd + 1e-9) {
          if (!nxt || t2 < nxt.startJD) nxt = { seasonID: s2, startJD: t2, year: yy2 };
        }
      }
    }
    return {
      seasonID: best.seasonID, name: SEASON_NAME[best.seasonID],
      startJD: best.startJD, endJD: nxt.startJD, nextName: SEASON_NAME[nxt.seasonID]
    };
  }

