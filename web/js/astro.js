  /* 黄经(度) → 地平坐标。lat 纬度(北正)、lonE 经度(东正)、jd 儒略日(UT)。
     方位角从北起算顺时针 0-360（北=0 东=90 南=180 西=270）；alt>0 在地平线上。
     黄纬按 0 处理（日月五星黄纬很小，对定宫足够）。 */
  function geoPos(lonDeg, latDeg, lonE, jd) {
    var eps = 23.4393;
    var lam = lonDeg * D2R;
    var ra = Math.atan2(Math.sin(lam) * Math.cos(eps * D2R), Math.cos(lam)) / D2R;
    var dec = Math.asin(Math.sin(lam) * Math.sin(eps * D2R)) / D2R;
    var n = jd - 2451545.0;
    var gmst = norm360(280.46061837 + 360.98564736629 * n);
    var lst = norm360(gmst + lonE);
    var H = norm360(lst - ra);
    var phi = latDeg * D2R, decR = dec * D2R, Hr = H * D2R;
    var alt = Math.asin(Math.sin(phi) * Math.sin(decR) + Math.cos(phi) * Math.cos(decR) * Math.cos(Hr)) / D2R;
    var az = norm360(Math.atan2(Math.sin(Hr), Math.cos(Hr) * Math.sin(phi) - Math.tan(decR) * Math.cos(phi)) / D2R + 180);
    return { az: az, alt: alt };
  }

  /* ---------------------------------------------------------- 地平坐标 */
  /* ---------------------------------------------------------------- 朔 */
  /* 月亮黄经 - 太阳黄经 = 0 的时刻（新月/朔）。jdGuess 附近迭代。 */
  function solveNewMoon(jdGuess) {
    var jd = jdGuess;
    for (var i = 0; i < 20; i++) {
      var elong = diff180(moonLongitude(jd) - sunLongitude(jd));  // 0=朔 180=望
      if (Math.abs(elong) < 1e-8) break;
      var step = -elong / 12.190749;    // 黄经差每天走约 12.19°，负号：elong>0 说明已过朔
      jd += step;
      if (Math.abs(step) < 1e-9) break;
    }
    return jd - deltaTDays(jd);                        // TT → UT
  }
  /* 取 jd 之后的第一个朔（含当天） */
  function newMoonAfter(jd) {
    // 1970-01-01 附近为朔，用 29.530588853 天的朔望月粗定
    var k = Math.floor((jd - 2451550.26) / 29.530588853);
    var guess = 2451550.26 + k * 29.530588853;
    var t = solveNewMoon(guess);
    while (t < jd) { guess += 29.530588853; t = solveNewMoon(guess); }
    return t;
  }
  function newMoonBefore(jd) {
    var t = newMoonAfter(jd);
    return solveNewMoon(t - 29.530588853);
  }

  var API = {
    D2R: D2R, R2D: R2D, norm360: norm360, diff180: diff180,
    julianDay: julianDay, fromJulian: fromJulian, weekday: weekday, deltaT: deltaT,
    sunLongitude: sunLongitude, moonLongitude: moonLongitude,
    solarTermJD: solarTermJD, solarTermsOfYear: solarTermsOfYear, seasonAt: seasonAt,
    SEASON_NAME: SEASON_NAME, SEASON_LON: SEASON_LON,
    solveNewMoon: solveNewMoon, newMoonAfter: newMoonAfter, newMoonBefore: newMoonBefore,
    geoPos: geoPos
  };
  root.Astro = API;
