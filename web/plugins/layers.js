/* ============================================================================
 * layers.js —— 「日月年家」插件（2026-11-02）
 * ----------------------------------------------------------------------------
 * 用户口径：年月日家那个设置去掉，做成插件。
 *
 * 这个插件**没有** palace / snap / head 之类渲染钩子 —— 四层排法本身在引擎里
 * （Qimen.castNian / castYue / castRi），宿主 ui.js 早就会按 state.layer 起盘，
 * 只是「要不要把四层切换露出来」原来由设置里的 layersOn 决定。
 *
 * 现在这件事交给插件：带一个**能力标志**
 *
 *     flags: { layers: true }
 *
 * 宿主 applyLayers() 读 Plugins.flagOn('layers')：
 *   开 → 起盘页顶部放出「时家 / 日家 / 月家 / 年家」四层切换；
 *   关 → 收回时家，那排切换不出现（插件缺键＝默认关，与其余插件同规矩）。
 *
 * 所以本文件除了注册没有别的代码；删掉它 = 四层功能从界面上消失（引擎不动）。
 * 契约见 web/plugins/README.md（flags 能力标志）。
 * ========================================================================== */
Plugins.register({
  id: 'layers',
  name: '日月年家',
  desc: '日家 / 月家 / 年家三层起盘。打开后起盘页顶部出现「时家 / 日家 / 月家 / 年家」四层切换，'
      + '时间仍用那张「日期 + 时刻」样件，按各自口径换算（年家按立春换年、月家按节气月、日家二至定阴阳）。',
  note: '理致有待考究，默认关。四层盘不排星曜（没有「某一刻」可依）；心盘会先收回时家。',
  flags: { layers: true }
});
